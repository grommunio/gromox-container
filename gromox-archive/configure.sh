# Idempotent gromox-archive configuration, applied on EVERY container start.

. /home/common/helpers
. /home/common/ssl_setup

log() { echo "$(date '+%Y-%m-%d %H:%M:%S') configure: $*" | tee -a "${LOGFILE}"; }

trust_shared_cert

# ── nginx ─────────────────────────────────────────────────────────
# 80 -> 8080, 443 -> 8443 so the container needs no privileges. The port is
# not published; gromox-core proxies /archive to ${ARCHIVE_HOST}:8443.
for f in /usr/share/grommunio-common/nginx.conf /etc/nginx/nginx.conf; do
  [ -f "$f" ] || continue
  sed -i 's/\blisten\s\+80\b/listen 8080/g; s/\blisten\s\+\[::\]:80\b/listen [::]:8080/g' "$f"
  sed -i 's/\blisten\s\+443\b/listen 8443/g; s/\blisten\s\+\[::\]:443\b/listen [::]:8443/g' "$f"
done
cat > /etc/nginx/conf.d/grommunio-container.conf <<'EOF'
# generated by gromox-container: listeners are remapped to high ports
port_in_redirect off;
client_max_body_size 512M;
EOF
install -d -m 0755 /etc/grommunio-common/nginx
cp -f /home/config/certificate.conf /etc/grommunio-common/nginx/ssl_certificate.conf

# ── PHP-FPM ───────────────────────────────────────────────────────
if [ -d /etc/php8 ] && [ -e /etc/php8/fpm/php-fpm.conf.default ] && [ ! -e /etc/php8/fpm/php-fpm.conf ]; then
  mv /etc/php8/fpm/php-fpm.conf.default /etc/php8/fpm/php-fpm.conf
fi

# ── piler (grommunio-archive) ─────────────────────────────────────
CONF=/etc/grommunio-archive/grommunio-archive.conf
if [ ! -s "${CONF}" ]; then
  cp -f /etc/grommunio-archive/grommunio-archive.conf.dist "${CONF}"
fi
setconf "${CONF}" mysqluser "${ARCHIVE_MYSQL_USER}"
setconf "${CONF}" mysqlpwd "${ARCHIVE_MYSQL_PASS}"
setconf "${CONF}" mysqldb "${ARCHIVE_MYSQL_DB}"
setconf "${CONF}" mysqlhost "${ARCHIVE_MYSQL_HOST}"
setconf "${CONF}" listen_addr 0.0.0.0
setconf "${CONF}" listen_port 2693
# piler stamps the retention onto each mail at store time: only affects newly archived mail
setconf "${CONF}" default_retention_days "${ARCHIVE_RETENTION_DAYS}"
chown root:groarchive "${CONF}"
chmod 0640 "${CONF}"

# Web UI configuration (carries the DB password)
# (the PHP single-quoted literal additionally needs ' and \ escaped)
PHP_PASS=$(sed_esc "$(printf '%s' "${ARCHIVE_MYSQL_PASS}" | sed -e "s/[\\\\']/\\\\&/g")")
sed -e "s#MYHOSTNAME#$(sed_esc "${FQDN}")#g" -e "s#MYSMTP#$(sed_esc "${DOMAIN}")#g" \
    -e "s#MYSQL_HOSTNAME#$(sed_esc "${ARCHIVE_MYSQL_HOST}")#" -e "s#MYSQL_DATABASE#$(sed_esc "${ARCHIVE_MYSQL_DB}")#" \
    -e "s#MYSQL_PASSWORD#${PHP_PASS}#" -e "s#MYSQL_USERNAME#$(sed_esc "${ARCHIVE_MYSQL_USER}")#" \
    /etc/grommunio-archive/config-site.dist.php > /etc/grommunio-archive/config-site.php
# restore-over-SMTP goes through the core postfix (the archive container has no MTA)
cat >> /etc/grommunio-archive/config-site.php <<EOF

\$config['SMARTHOST'] = '${CORE_HOST:-gromox-core}';
\$config['SMARTHOST_PORT'] = 2525;
EOF
chown root:groarchive /etc/grommunio-archive/config-site.php
chmod 0640 /etc/grommunio-archive/config-site.php

# ── Sphinx ────────────────────────────────────────────────────────
php /etc/grommunio-archive/sphinx.conf.dist > /etc/sphinx/sphinx.conf
sed -i -e "s#MYSQL_HOSTNAME#$(sed_esc "${ARCHIVE_MYSQL_HOST}")#" -e "s#MYSQL_DATABASE#$(sed_esc "${ARCHIVE_MYSQL_DB}")#" \
       -e "s#MYSQL_PASSWORD#$(sed_esc "${ARCHIVE_MYSQL_PASS}")#" -e "s#MYSQL_USERNAME#$(sed_esc "${ARCHIVE_MYSQL_USER}")#" /etc/sphinx/sphinx.conf
chown groarchive:sphinx /etc/sphinx/sphinx.conf
chmod 0640 /etc/sphinx/sphinx.conf
install -d -m 0775 -o groarchive -g sphinx /var/lib/grommunio-archive/sphinx
chown -R groarchive:sphinx /var/lib/grommunio-archive/sphinx
for d in store tmp stat error imap; do
  install -d -o groarchive -g grommunio "/var/lib/grommunio-archive/${d}"
done
# The encryption key lives with the store on the archive_data volume; piler
# reads it from its compiled-in path.
ln -sfn /var/lib/grommunio-archive/grommunio-archive.key /etc/grommunio-archive/grommunio-archive.key

if ! nginx -t >/dev/null 2>&1; then
  log "WARNING: nginx configuration test failed:"
  nginx -t 2>&1 | tee -a "${LOGFILE}"
fi

exit 0
