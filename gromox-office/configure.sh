# Idempotent gromox-office configuration, applied on EVERY container start.

. /home/common/helpers
. /home/common/ssl_setup

log() { echo "$(date '+%Y-%m-%d %H:%M:%S') configure: $*" | tee -a "${LOGFILE}"; }
occ() { ( cd /usr/share/grommunio-files && sudo -u grofiles ./occ -n -q "$@" ) >>"${LOGFILE}" 2>&1; }

trust_shared_cert

# ── nginx ─────────────────────────────────────────────────────────
# 80 -> 8080, 443 -> 8443 so the container needs no privileges. The port is
# not published; gromox-core proxies /files and /office to ${OFFICE_HOST}:8443.
for f in /usr/share/grommunio-common/nginx.conf /etc/nginx/nginx.conf; do
  [ -f "$f" ] || continue
  sed -i 's/\blisten\s\+80\b/listen 8080/g; s/\blisten\s\+\[::\]:80\b/listen [::]:8080/g' "$f"
  sed -i 's/\blisten\s\+443\b/listen 8443/g; s/\blisten\s\+\[::\]:443\b/listen [::]:8443/g' "$f"
done
cat > /etc/nginx/conf.d/grommunio-container.conf <<'EOF'
# generated by gromox-container: listeners are remapped to high ports
port_in_redirect off;
client_max_body_size 512M;
EOF
install -d -m 0755 /etc/grommunio-common/nginx
cp -f /home/config/certificate.conf /etc/grommunio-common/nginx/ssl_certificate.conf

# ── PHP ───────────────────────────────────────────────────────────
if [ -d /etc/php8 ]; then
  if [ -e /etc/php8/fpm/php-fpm.conf.default ] && [ ! -e /etc/php8/fpm/php-fpm.conf ]; then
    mv /etc/php8/fpm/php-fpm.conf.default /etc/php8/fpm/php-fpm.conf
  fi
  sed -i -e 's/^memory_limit = 128M/memory_limit = 512M/' /etc/php8/cli/php.ini
fi

# ── grommunio Files ───────────────────────────────────────────────
if [ "${ENABLE_FILES}" = "true" ]; then
  INSTALLED=$( (cd /usr/share/grommunio-files && sudo -u grofiles ./occ -n status --output=json 2>/dev/null) | jq -r '.installed' 2>/dev/null)
  if [ "${INSTALLED}" = "true" ]; then
    # A package update may have bumped the schema; web upgrade is disabled.
    occ upgrade
    occ maintenance:mode --off
    occ config:system:set trusted_domains 1 --value="${FQDN}"
    occ config:system:set trusted_domains 2 --value="${DOMAIN}"
    occ config:system:set trusted_domains 3 --value="mail.${DOMAIN}"
    # host only: overwritewebroot (/files) is appended by Files itself
    occ config:system:set overwrite.cli.url --value="https://${FQDN}"
    occ config:system:set overwriteprotocol --value="https"
    # Requests arrive through the gromox-core reverse proxy
    i=0
    for p in ${TRUSTED_PROXIES}; do
      occ config:system:set trusted_proxies "${i}" --value="${p}"
      i=$((i+1))
    done
    # Authenticate Files users against grommunio (DAV basic auth)
    occ app:enable user_external
    occ config:system:set user_backends 0 arguments 0 --value="https://${FQDN}/dav"
    occ config:system:set user_backends 0 class --value='\OCA\UserExternal\BasicAuth'
    occ config:system:set integrity.check.disabled --type boolean --value true
    occ config:system:set allow_local_remote_servers --type boolean --value true
    occ config:system:set check_for_working_wellknown_setup --type boolean --value false
    occ config:system:set maintenance_window_start --type integer --value 1
    # Notification mail goes through the core postfix
    occ config:system:set mail_from_address --value='admin'
    occ config:system:set mail_smtpmode --value='smtp'
    occ config:system:set mail_domain --value="${DOMAIN}"
    occ config:system:set mail_smtphost --value="${CORE_HOST}"
    occ config:system:set mail_smtpport --type integer --value 2525
    occ background:cron
    if [ "${ENABLE_OFFICE}" = "true" ]; then
      occ app:enable onlyoffice
      occ config:system:set --type boolean --value="true" csrf.disabled
      occ config:app:set onlyoffice DocumentServerUrl --value="https://${FQDN}/office/"
      # the document server runs in this container: talk to it directly
      occ config:app:set onlyoffice DocumentServerInternalUrl --value="http://localhost:8000/"
      occ config:app:delete onlyoffice StorageUrl
      # requests between Files and the document server are signed (JWT)
      occ config:app:set onlyoffice jwt_secret --value="${OFFICE_JWT_SECRET}"
      occ config:app:set onlyoffice jwt_header --value="Authorization"
      occ config:app:set onlyoffice customizationChat --value=false
      occ config:app:set onlyoffice customizationCompactHeader --value=true
      occ config:app:set onlyoffice customizationFeedback --value=false
      occ config:app:set onlyoffice customizationToolbarNoTabs --value=true
      occ config:app:set onlyoffice preview --value=false
      occ config:app:set onlyoffice sameTab --value=true
    fi
  else
    log "WARNING: grommunio Files is not installed; skipping its configuration"
  fi
  echo "*/5 * * * * grofiles /usr/bin/php -f /usr/share/grommunio-files/cron.php" > /etc/cron.d/grommunio-files
else
  rm -f /etc/cron.d/grommunio-files
fi

# ── grommunio Office (document server) ────────────────────────────
if [ "${ENABLE_OFFICE}" = "true" ]; then
  TMP=$(mktemp)
  jq --arg h "${OFFICE_MYSQL_HOST}" --arg n "${OFFICE_MYSQL_DB}" --arg u "${OFFICE_MYSQL_USER}" --arg p "${OFFICE_MYSQL_PASS}" --arg s "${OFFICE_JWT_SECRET}" \
     '.services.CoAuthoring.sql.dbHost=$h | .services.CoAuthoring.sql.dbName=$n | .services.CoAuthoring.sql.dbUser=$u | .services.CoAuthoring.sql.dbPass=$p |
      .services.CoAuthoring.token.enable.browser=true | .services.CoAuthoring.token.enable.request.inbox=true | .services.CoAuthoring.token.enable.request.outbox=true |
      .services.CoAuthoring.secret.browser.string=$s | .services.CoAuthoring.secret.inbox.string=$s | .services.CoAuthoring.secret.outbox.string=$s | .services.CoAuthoring.secret.session.string=$s' \
     /etc/grommunio-office/default.json > "${TMP}"
  if [ -s "${TMP}" ]; then
    cat "${TMP}" > /etc/grommunio-office/default.json
  else
    log "WARNING: could not update /etc/grommunio-office/default.json"
  fi
  rm -f "${TMP}"
  chown root:groffice /etc/grommunio-office/default.json
  chmod 0640 /etc/grommunio-office/default.json
  chown -R groffice:groffice /var/lib/grommunio-office 2>/dev/null || true
  sed -i 's/^autostart=false/autostart=true/' /etc/supervisor.d/ds-docservice.conf /etc/supervisor.d/ds-converter.conf /etc/supervisor.d/rabbitmq.conf
else
  sed -i 's/^autostart=true/autostart=false/' /etc/supervisor.d/ds-docservice.conf /etc/supervisor.d/ds-converter.conf /etc/supervisor.d/rabbitmq.conf
fi

if ! nginx -t >/dev/null 2>&1; then
  log "WARNING: nginx configuration test failed:"
  nginx -t 2>&1 | tee -a "${LOGFILE}"
fi

exit 0
