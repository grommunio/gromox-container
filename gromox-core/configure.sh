# Idempotent gromox-core configuration, applied on EVERY container start.
#
# Everything here is derived from the environment (var.env) and from state
# on persistent volumes (certificates, X500 id). Nothing in this script
# creates or drops databases or sets passwords of existing accounts - that
# is the job of the one-time entrypoint.sh. Keeping it idempotent is what
# makes a recreated container (image update, "docker compose up" after a
# var.env change) come up fully configured.

. /home/common/helpers
. /home/common/ssl_setup

log() { echo "$(date '+%Y-%m-%d %H:%M:%S') configure: $*" | tee -a "${LOGFILE}"; }

# ── Certificates ──────────────────────────────────────────────────
if [ "${SSL_INSTALL_TYPE}" = "3" ]; then
  # Own certificate provided by the operator: keep the shared copy current
  owncert >>"${LOGFILE}" 2>&1 || log "WARNING: SSL_INSTALL_TYPE=3 but SSL_BUNDLE/SSL_KEY are not readable"
elif [ "${SSL_INSTALL_TYPE}" = "2" ] && [ -s "${SSL_BUNDLE_T}" ]; then
  # A failed first certbot run (DNS, port 80) must not leave the built-in CA
  # certificate forever: retry while no Let's Encrypt lineage exists (at most
  # once per hour, to stay clear of the rate limits).
  le_setup_vars
  if [ ! -f "/etc/letsencrypt/live/${FQDN}/fullchain.pem" ] && le_retry_due; then
    log "No Let's Encrypt certificate yet, retrying certbot"
    letsencrypt
  fi
fi
if [ -s "${SSL_BUNDLE_T}" ] && [ -s "${SSL_KEY_T}" ]; then
  if [ "${SSL_INSTALL_TYPE}" = "0" ] && { [ ! -s "${SSL_CA_CRT}" ] || builtin_cert_expiring; }; then
    log "Issuing the server certificate from the built-in CA"
    selfcert
  fi
  chown gromox:gromox "${SSL_BUNDLE_T}" "${SSL_KEY_T}" 2>/dev/null || true
  chmod 0644 "${SSL_BUNDLE_T}"
  chmod 0600 "${SSL_KEY_T}"
  # Make the built-in CA (SSL_INSTALL_TYPE=0) trusted inside the
  # container: admin-api -> chat, Files -> DAV etc. connect to the public FQDN.
  trust_shared_cert
else
  log "WARNING: no TLS certificate at ${SSL_BUNDLE_T}; nginx and the TLS listeners will fail to start"
fi

# ── nginx ─────────────────────────────────────────────────────────
# The public listeners move above 1024 so the container needs no privileges:
# web 80 -> 8081, 443 -> 8443; admin TLS 8443 -> 9443. The admin HTTP listener
# stays on its packaged port 8080, which grommunio-web (passwd/mdm plugins)
# and admin-api (statusmonitor) use internally.
for f in /usr/share/grommunio-common/nginx.conf /etc/nginx/nginx.conf; do
  [ -f "$f" ] || continue
  sed -i 's/\blisten\s\+80\b/listen 8081/g; s/\blisten\s\+\[::\]:80\b/listen [::]:8081/g' "$f"
  sed -i 's/\blisten\s\+8080\b/listen 8081/g; s/\blisten\s\+\[::\]:8080\b/listen [::]:8081/g' "$f"
  sed -i 's/\blisten\s\+443\b/listen 8443/g; s/\blisten\s\+\[::\]:443\b/listen [::]:8443/g' "$f"
done
if [ -f /usr/share/grommunio-admin-common/nginx.conf ]; then
  # undo the remap older versions applied to the admin HTTP listener
  sed -i 's/\blisten\s\+9080\b/listen 8080/g; s/\blisten\s\+\[::\]:9080\b/listen [::]:8080/g' \
    /usr/share/grommunio-admin-common/nginx.conf
fi
if [ -f /usr/share/grommunio-admin-common/nginx-ssl.conf ]; then
  sed -i 's/\blisten\s\+8443\b/listen 9443/g; s/\blisten\s\+\[::\]:8443\b/listen [::]:9443/g' \
    /usr/share/grommunio-admin-common/nginx-ssl.conf
fi
if [ -f /etc/grommunio-web/config-passwd.php ]; then
  sed -i 's#:9080/api/v1/passwd#:8080/api/v1/passwd#' /etc/grommunio-web/config-passwd.php
fi

# nginx builds redirects from the port it listens on; behind the port remap
# that would send browsers to https://FQDN:8443/web/ (the admin UI port).
# The resolver lets proxy_pass targets (archive/office containers) be looked
# up at request time, so nginx starts even while they are still down.
cat > /etc/nginx/conf.d/grommunio-container.conf <<'EOF'
# generated by gromox-container: listeners are remapped to high ports
port_in_redirect off;
resolver 127.0.0.11 valid=30s ipv6=off;
EOF

# TLS include shared by the web and the admin server blocks
install -d -m 0755 /etc/grommunio-common/nginx/locations.d /etc/grommunio-common/nginx/upstreams.d /etc/grommunio-admin-common/nginx.d
cp -f /home/config/certificate.conf /etc/grommunio-common/nginx/ssl_certificate.conf
ln -sfn /etc/grommunio-common/nginx/ssl_certificate.conf /etc/grommunio-admin-common/nginx-ssl.conf

# Serve the admin-web runtime configuration
cat > /etc/grommunio-admin-common/nginx.d/web-config.conf <<'EOF'
location /config.json {
  alias /etc/grommunio-admin-common/config.json;
}
EOF

# Location blocks for the optional containers. They live in /etc (included by
# grommunio-common's nginx.conf) so they can be regenerated here; the copies
# older versions wrote into /usr/share would duplicate them.
rm -f /usr/share/grommunio-common/nginx/locations.d/grommunio-files.conf \
      /usr/share/grommunio-common/nginx/locations.d/grommunio-office.conf \
      /usr/share/grommunio-common/nginx/locations.d/grommunio-archive.conf \
      /usr/share/grommunio-common/nginx/upstreams.d/grommunio-archive.conf \
      /etc/grommunio-common/nginx/upstreams.d/grommunio-archive.conf

if [ "${ENABLE_FILES}" = "true" ]; then
cat > /etc/grommunio-common/nginx/locations.d/grommunio-files.conf <<EOF
location ^~ /files {
	set \$files_upstream https://${FILES_HOST:-${OFFICE_HOST}}:8443;
	proxy_pass \$files_upstream;
	# proxy_set_header in a location disables inheritance of the server-level headers
	include /usr/share/grommunio-common/nginx/proxy_headers.conf;
	proxy_set_header X-Forwarded-Proto https;
	client_max_body_size 512M;
	proxy_request_buffering off;
	proxy_buffering off;
	proxy_read_timeout 3600s;
	proxy_send_timeout 3600s;
	error_log /var/log/nginx/nginx-files-error.log;
	access_log /var/log/nginx/nginx-files-access.log;
}
EOF
else
  rm -f /etc/grommunio-common/nginx/locations.d/grommunio-files.conf
fi

if [ "${ENABLE_OFFICE}" = "true" ]; then
cat > /etc/grommunio-common/nginx/locations.d/grommunio-office.conf <<EOF
location  /cache/ {
  rewrite /cache/(.*)$ /office/cache/\$1;
}
location  /office/ {
  set \$office_upstream https://${OFFICE_HOST}:8443;
  proxy_pass         \$office_upstream;
  proxy_http_version 1.1;
  client_max_body_size 512M;
  proxy_read_timeout 3600s;
  include /usr/share/grommunio-common/nginx/proxy_headers.conf;
  proxy_set_header Upgrade \$http_upgrade;
  proxy_set_header Connection \$proxy_connection;
  # the office container's own nginx appends /office to the forwarded host
  proxy_set_header X-Forwarded-Host \$the_host;
  proxy_set_header X-Forwarded-Proto \$the_scheme;
  access_log /var/log/nginx/nginx-office-access.log;
  error_log /var/log/nginx/nginx-office-error.log;
}
EOF
else
  rm -f /etc/grommunio-common/nginx/locations.d/grommunio-office.conf
fi

if [ "${ENABLE_ARCHIVE}" = "true" ]; then
# The archive container's packaged nginx configuration does the PHP routing;
# this only forwards everything below /archive to it.
cat > /etc/grommunio-common/nginx/locations.d/grommunio-archive.conf <<EOF
location ^~ /archive {
	set \$archive_upstream https://${ARCHIVE_HOST}:8443;
	proxy_pass \$archive_upstream;
	include /usr/share/grommunio-common/nginx/proxy_headers.conf;
	proxy_set_header X-Forwarded-Proto https;
	client_max_body_size 512M;
	proxy_request_buffering off;
	proxy_buffering off;
	proxy_read_timeout 600s;
	error_log /var/log/nginx/nginx-archive-error.log;
	access_log /var/log/nginx/nginx-archive-access.log;
}
EOF
else
  rm -f /etc/grommunio-common/nginx/locations.d/grommunio-archive.conf
fi

# ── admin-web / admin-api ─────────────────────────────────────────
# Links shown in the admin UI top bar. Trailing slashes avoid a directory
# redirect on the target.
CFG=$(jq -n --arg mail "https://${FQDN}/web/" --arg rspamd "https://${FQDN}:8443/antispam/" \
      '{mailWebAddress: $mail, rspamdWebAddress: $rspamd}')
[ "${ENABLE_CHAT}" = "true" ]    && CFG=$(echo "${CFG}" | jq --arg u "https://${FQDN}/chat/"    '.chatWebAddress = $u')
[ "${ENABLE_FILES}" = "true" ]   && CFG=$(echo "${CFG}" | jq --arg u "https://${FQDN}/files/"   '.fileWebAddress = $u')
[ "${ENABLE_ARCHIVE}" = "true" ] && CFG=$(echo "${CFG}" | jq --arg u "https://${FQDN}/archive/" '.archiveWebAddress = $u')
echo "${CFG}" > /etc/grommunio-admin-common/config.json
chmod 0644 /etc/grommunio-admin-common/config.json

# The JWT signing key of the admin API lives on the grommunio_admin_config
# volume: it must not be shared between deployments built from one image.
install -d -m 0750 -o grommunio -g grommunio /etc/grommunio-admin-api/conf.d
if [ ! -s /etc/grommunio-admin-api/jwt-privkey.pem ] || [ ! -s /etc/grommunio-admin-api/jwt-pubkey.pem ]; then
  log "Generating admin API JWT signing key"
  rm -f /etc/grommunio-admin-api/jwt-privkey.pem /etc/grommunio-admin-api/jwt-pubkey.pem
  openssl genrsa -out /etc/grommunio-admin-api/jwt-privkey.pem 4096 >>"${LOGFILE}" 2>&1
  openssl rsa -in /etc/grommunio-admin-api/jwt-privkey.pem -outform PEM -pubout -out /etc/grommunio-admin-api/jwt-pubkey.pem >>"${LOGFILE}" 2>&1
fi
chown grommunio:grommunio /etc/grommunio-admin-api/jwt-privkey.pem /etc/grommunio-admin-api/jwt-pubkey.pem
chmod 0600 /etc/grommunio-admin-api/jwt-privkey.pem
chmod 0644 /etc/grommunio-admin-api/jwt-pubkey.pem

generate_admin_db_conf "/etc/grommunio-admin-api/conf.d/database.yaml"
chown grommunio:grommunio /etc/grommunio-admin-api/conf.d/database.yaml
chmod 0640 /etc/grommunio-admin-api/conf.d/database.yaml
if [ "${ENABLE_CHAT}" = "true" ]; then
  # chat runs in this container: talk to it directly instead of through the
  # public FQDN (no hairpin NAT, no TLS verification issues)
  generate_admin_chat_conf "/etc/grommunio-admin-api/conf.d/chat.yaml"
  chown grommunio:grommunio /etc/grommunio-admin-api/conf.d/chat.yaml
  chmod 0640 /etc/grommunio-admin-api/conf.d/chat.yaml
else
  rm -f /etc/grommunio-admin-api/conf.d/chat.yaml
fi
# admin-api runs as grommunio (like the packaged unit); older images ran it as
# root and may have left root-owned state behind.
chown -R grommunio:grommunio /var/lib/grommunio-admin-api /etc/grommunio-admin-common/license 2>/dev/null || true

# rspamd web UI password (admin UI -> Antispam), same as ADMIN_PASS
rspamadm pw -p "${ADMIN_PASS}" | sed -e 's#^#password = "#' -e 's#$#";#' > /etc/grommunio-antispam/local.d/worker-controller.inc
chown root:grommunio /etc/grommunio-antispam/local.d/worker-controller.inc
chmod 0640 /etc/grommunio-antispam/local.d/worker-controller.inc

# ── PHP-FPM ───────────────────────────────────────────────────────
if [ -d /etc/php8 ]; then
  if [ -e /etc/php8/fpm/php-fpm.conf.default ] && [ ! -e /etc/php8/fpm/php-fpm.conf ]; then
    mv /etc/php8/fpm/php-fpm.conf.default /etc/php8/fpm/php-fpm.conf
  fi
  cp -f /usr/share/gromox/fpm-gromox.conf.sample /etc/php8/fpm/php-fpm.d/gromox.conf
fi

# ── PAM for SMTP AUTH (saslauthd -> pam_gromox) ───────────────────
cp -f /home/config/smtp /etc/pam.d/smtp

# ── gromox ────────────────────────────────────────────────────────
X500_FILE="/etc/gromox/.x500_org"
X500="${X500:-$(cat "${X500_FILE}" 2>/dev/null)}"

CFG=/etc/gromox/mysql_adaptor.cfg
touch "${CFG}"
setconf "${CFG}" mysql_username "${MYSQL_USER}"
setconf "${CFG}" mysql_password "${MYSQL_PASS}"
setconf "${CFG}" mysql_dbname "${MYSQL_DB}"
setconf "${CFG}" mysql_host "${MYSQL_HOST}"
# gromox-http upgrades the DB schema itself when the installed package is newer
setconf "${CFG}" schema_upgrade "host:${FQDN}"
chmod 0640 "${CFG}"
chgrp gromoxcf "${CFG}" 2>/dev/null || true

touch /etc/gromox/gromox.cfg
# nginx terminates the client connection; let gromox log the real client IP
setconf /etc/gromox/gromox.cfg http_remote_host_hdr X-Real-IP
# local delivery agent, fed by postfix via virtual_transport; loopback only
setconf /etc/gromox/gromox.cfg lda_listen 127.0.0.1:24
# mail composed in webmail/MAPI/EWS/ActiveSync enters postfix through smtpd
# (milter, archive envelope) instead of the sendmail maildrop
setconf /etc/gromox/gromox.cfg outgoing_smtp_url smtp://127.0.0.1:2525
sed -i '/^listen_port[[:space:]]*=/d; /^listen_addr[[:space:]]*=/d' /etc/gromox/smtp.cfg 2>/dev/null

setconf /etc/gromox/http.cfg listen_port 10080
setconf /etc/gromox/http.cfg http_support_ssl true
setconf /etc/gromox/http.cfg listen_ssl_port 10443
setconf /etc/gromox/http.cfg host_id "${FQDN}"
setconf /etc/gromox/http.cfg http_certificate_path "${SSL_BUNDLE_T}"
setconf /etc/gromox/http.cfg http_private_key_path "${SSL_KEY_T}"
setconf /etc/gromox/http.cfg tls_min_proto tls1.2

# IMAP/POP3 listen directly on the published high ports
setconf /etc/gromox/imap.cfg imap_support_starttls true
setconf /etc/gromox/imap.cfg listen_port 2143
setconf /etc/gromox/imap.cfg listen_ssl_port 2993
setconf /etc/gromox/imap.cfg imap_certificate_path "${SSL_BUNDLE_T}"
setconf /etc/gromox/imap.cfg imap_private_key_path "${SSL_KEY_T}"
setconf /etc/gromox/imap.cfg tls_min_proto tls1.2

setconf /etc/gromox/pop3.cfg pop3_support_stls true
setconf /etc/gromox/pop3.cfg listen_port 2110
setconf /etc/gromox/pop3.cfg listen_ssl_port 2995
setconf /etc/gromox/pop3.cfg pop3_certificate_path "${SSL_BUNDLE_T}"
setconf /etc/gromox/pop3.cfg pop3_private_key_path "${SSL_KEY_T}"
setconf /etc/gromox/pop3.cfg tls_min_proto tls1.2

for SERVICE in http midb zcore imap pop3 smtp delivery ; do
  setconf /etc/gromox/${SERVICE}.cfg default_domain "${DOMAIN}"
done
if [ -n "${X500}" ]; then
  for CFG in gromox.cfg autodiscover.cfg midb.cfg zcore.cfg exmdb_local.cfg exmdb_provider.cfg exchange_emsmdb.cfg exchange_nsp.cfg ; do
    setconf "/etc/gromox/${CFG}" x500_org_name "${X500}"
  done
fi

# gromox-event/-timer run as gromox (like their units) and need their queue
chown -R gromox:gromox /var/lib/gromox/queue 2>/dev/null || true
chown grodav:grodav /var/lib/grommunio-dav 2>/dev/null || true

# ── Postfix ───────────────────────────────────────────────────────
# _utf8mb4 introducer + explicit collation: the gromox columns are ascii and
# postfix sends utf8mb4 keys (same as grommunio-setup)
generate_g_cf_files "/etc/postfix/grommunio-virtual-mailbox-domains.cf" "SELECT 1 FROM domains WHERE domain_status=0 AND domainname=_utf8mb4'%s' COLLATE utf8mb4_general_ci"
generate_g_cf_files "/etc/postfix/grommunio-virtual-mailbox-alias-maps.cf" "SELECT mainname FROM aliases WHERE aliasname=_utf8mb4'%s' COLLATE utf8mb4_general_ci UNION SELECT destination FROM forwards WHERE username=_utf8mb4'%s' COLLATE utf8mb4_general_ci AND forward_type = 1"
generate_g_cf_files "/etc/postfix/grommunio-virtual-mailbox-maps.cf" "SELECT 1 FROM users WHERE username=_utf8mb4'%s' COLLATE utf8mb4_general_ci"
generate_g_cf_files "/etc/postfix/grommunio-bcc-forwards.cf" "SELECT destination FROM forwards WHERE username=_utf8mb4'%s' COLLATE utf8mb4_general_ci AND forward_type = 0"
chown root:postfix /etc/postfix/grommunio-*.cf
chmod 0640 /etc/postfix/grommunio-*.cf

# Trusted networks: loopback and the compose network (archive/office relay
# through this postfix), but NOT the network gateways: connections proxied by
# Docker from the host (loopback, IPv6 without ip6tables) arrive from there
# and must not be allowed to relay without authentication.
MYNETWORKS="127.0.0.0/8 [::1]/128"
for gw in $(ip -4 route show default 2>/dev/null | awk '{print $3}'); do MYNETWORKS="${MYNETWORKS} !${gw}"; done
for gw in $(ip -6 route show default 2>/dev/null | awk '{print $3}'); do MYNETWORKS="${MYNETWORKS} ![${gw}]"; done
for net in $(ip -4 route show scope link 2>/dev/null | awk '/\// {print $1}'); do MYNETWORKS="${MYNETWORKS} ${net}"; done
for net in $(ip -6 route show 2>/dev/null | awk '/^f[cd][0-9a-f]{2}:.*\/[0-9]+ dev/ {print $1}'); do MYNETWORKS="${MYNETWORKS} [${net%/*}]/${net#*/}"; done

CORE_RCPT_RESTRICTIONS="permit_sasl_authenticated,permit_mynetworks,reject_unknown_recipient_domain,reject_non_fqdn_hostname,reject_non_fqdn_sender,reject_non_fqdn_recipient,reject_unauth_destination,reject_unauth_pipelining"
TLS_PROTOCOLS='!SSLv2,!SSLv3,!TLSv1,!TLSv1.1'
TLS_EXCLUDE_CIPHERS="aNULL,eNULL,EXP,MD5,RC4,DES,3DES,DHE,EDH,kDHE,kEDH,ADH"

postconf -e \
  myhostname="${FQDN}" \
  maillog_file=/dev/stdout \
  smtp_bind_address= \
  inet_protocols=all \
  mynetworks="${MYNETWORKS}" \
  always_add_missing_headers=yes \
  local_header_rewrite_clients=permit_inet_interfaces,permit_mynetworks,permit_sasl_authenticated \
  virtual_mailbox_domains="mysql:/etc/postfix/grommunio-virtual-mailbox-domains.cf" \
  virtual_mailbox_maps="mysql:/etc/postfix/grommunio-virtual-mailbox-maps.cf" \
  virtual_alias_maps="mysql:/etc/postfix/grommunio-virtual-mailbox-alias-maps.cf" \
  recipient_bcc_maps="mysql:/etc/postfix/grommunio-bcc-forwards.cf" \
  unverified_recipient_reject_code=550 \
  virtual_transport="smtp:[127.0.0.1]:24" \
  relayhost="${RELAYHOST:-}" \
  inet_interfaces=all \
  smtpd_helo_restrictions=permit_mynetworks,permit_sasl_authenticated,reject_invalid_hostname,reject_non_fqdn_hostname \
  smtpd_sender_restrictions=reject_non_fqdn_sender,permit_sasl_authenticated,permit_mynetworks \
  smtpd_recipient_restrictions="${CORE_RCPT_RESTRICTIONS}" \
  smtpd_data_restrictions=reject_unauth_pipelining \
  smtpd_discard_ehlo_keywords=chunking \
  smtpd_tls_security_level=may \
  smtpd_tls_auth_only=yes \
  smtpd_tls_cert_file="${SSL_BUNDLE_T}" \
  smtpd_tls_key_file="${SSL_KEY_T}" \
  smtpd_tls_received_header=yes \
  smtpd_tls_session_cache_timeout=3600s \
  smtpd_tls_mandatory_protocols="${TLS_PROTOCOLS}" \
  smtpd_tls_protocols="${TLS_PROTOCOLS}" \
  smtpd_tls_exclude_ciphers="${TLS_EXCLUDE_CIPHERS}" \
  tls_preempt_cipherlist=yes \
  tls_random_source=dev:/dev/urandom \
  smtpd_sasl_auth_enable=yes \
  broken_sasl_auth_clients=yes \
  smtpd_sasl_security_options=noanonymous \
  smtpd_sasl_local_domain= \
  smtpd_milters=inet:127.0.0.1:11332 \
  milter_default_action=accept \
  milter_protocol=6 \
  smtp_tls_security_level=may

# master.cf: the stock listeners (25/587/465) are replaced by ones on the
# published high ports. Using the port number as service name is the
# standard postfix way to bind a non-default port.
for svc in smtp submission smtps; do
  postconf -MX "${svc}/inet" >/dev/null 2>&1 || true
done
postconf -M tlsmgr/unix="tlsmgr unix - - n 1000? 1 tlsmgr"
postconf -M 2525/inet="2525 inet n - n - - smtpd"
postconf -P 2525/inet/syslog_name="postfix/smtp"
postconf -M 2587/inet="2587 inet n - n - - smtpd"
postconf -P \
  2587/inet/syslog_name="postfix/submission" \
  2587/inet/smtpd_tls_security_level=encrypt \
  2587/inet/smtpd_tls_mandatory_protocols="${TLS_PROTOCOLS}" \
  2587/inet/smtpd_tls_protocols="${TLS_PROTOCOLS}" \
  2587/inet/smtpd_tls_exclude_ciphers="${TLS_EXCLUDE_CIPHERS}" \
  2587/inet/smtpd_sasl_auth_enable=yes \
  2587/inet/smtpd_relay_restrictions=permit_sasl_authenticated,reject \
  2587/inet/milter_macro_daemon_name=ORIGINATING
postconf -M 2465/inet="2465 inet n - n - - smtpd"
postconf -P \
  2465/inet/syslog_name="postfix/smtps" \
  2465/inet/smtpd_tls_wrappermode=yes \
  2465/inet/smtpd_tls_mandatory_protocols="${TLS_PROTOCOLS}" \
  2465/inet/smtpd_tls_protocols="${TLS_PROTOCOLS}" \
  2465/inet/smtpd_tls_exclude_ciphers="${TLS_EXCLUDE_CIPHERS}" \
  2465/inet/smtpd_sasl_auth_enable=yes \
  2465/inet/smtpd_relay_restrictions=permit_sasl_authenticated,reject \
  2465/inet/milter_macro_daemon_name=ORIGINATING

# Compile lmdb maps shipped as plain-text by the postfix package
for m in relay relay_recipients; do
  [ -f "/etc/postfix/${m}" ] && postmap "lmdb:/etc/postfix/${m}"
done

if [ "${ENABLE_ARCHIVE}" = "true" ]; then
  # Every recipient is recorded in an X-Envelope-To header for the archiver,
  # also for authenticated/internal senders (so Bcc recipients of outbound
  # mail are archived). The header is only meant for the archive copy: the
  # dedicated "archive" transport keeps it, all other deliveries strip it so
  # that Bcc recipients are not disclosed.
  echo "/(.*)/   prepend X-Envelope-To: \$1" > /etc/postfix/grommunio-archiver-envelope.cf
  echo "/^X-Envelope-To:/ IGNORE" > /etc/postfix/grommunio-archiver-strip.pcre
  postconf -e "smtpd_recipient_restrictions=check_recipient_access pcre:/etc/postfix/grommunio-archiver-envelope.cf,${CORE_RCPT_RESTRICTIONS}"
  postconf -e "always_bcc=archive@${FQDN}" \
              "smtp_header_checks=pcre:/etc/postfix/grommunio-archiver-strip.pcre"
  postconf -M archive/unix="archive unix - - n - - smtp"
  postconf -P archive/unix/smtp_header_checks= archive/unix/syslog_name="postfix/archive" archive/unix/smtp_address_preference=ipv4
