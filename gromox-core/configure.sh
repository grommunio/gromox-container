# ── Keycloak ──────────────────────────────────────────────────────
if [ "${ENABLE_KEYCLOAK}" = "true" ] ; then
  # Fetch bearer public key from Keycloak JWKS endpoint
  JWKS_URL="${KEYCLOAK_URL%/}/realms/${KEYCLOAK_REALM}/protocol/openid-connect/certs"
  JWKS_RESPONSE=$(curl -sf "${JWKS_URL}" || true)
  BEARER_PUBKEY=""
  if [ -n "${JWKS_RESPONSE}" ]; then
    echo "${JWKS_RESPONSE}" \
      | jq -r '[.keys[] | select(.alg=="RS256" and .use=="sig")][0].x5c[0]' \
      | base64 -d > /tmp/keycloak_cert.der 2>/dev/null
    BEARER_PUBKEY=$(openssl x509 -inform DER -in /tmp/keycloak_cert.der -pubkey -noout 2>/dev/null || true)
    rm -f /tmp/keycloak_cert.der
  fi

  if [ -z "${BEARER_PUBKEY}" ]; then
    log "WARNING: Could not fetch bearer public key from ${JWKS_URL}"
  else
    echo "${BEARER_PUBKEY}" > /etc/gromox/bearer_pubkey
    chmod 644 /etc/gromox/bearer_pubkey
  fi

  PUBKEY_CLEAN=$(echo "${BEARER_PUBKEY}" | grep -v '^-----' | tr -d '\n')
  jq -n \
    --arg realm "${KEYCLOAK_REALM}" \
    --arg url "${KEYCLOAK_URL}" \
    --arg client "${KEYCLOAK_CLIENT_ID}" \
    --arg secret "${KEYCLOAK_CLIENT_SECRET}" \
    --arg pubkey "${PUBKEY_CLEAN}" \
    '{
      "realm": $realm,
      "auth-server-url": $url,
      "resource": $client,
      "credentials": { "secret": $secret },
      "confidential-port": 0,
      "realm-public-key": $pubkey
    }' > /etc/gromox/keycloak.json
  # read by grommunio-web (php-fpm pool runs as groweb)
  chmod 0640 /etc/gromox/keycloak.json
  chown root:groweb /etc/gromox/keycloak.json 2>/dev/null || true

  jq --arg client "${KEYCLOAK_CLIENT_ID}" --arg fqdn "${FQDN}" \
    '(.clientId, .name) = $client |
     .description = "Client for \($client) SSO" |
     .rootUrl = "https://\($fqdn)/" |
     .adminUrl = "https://\($fqdn)/" |
     .baseUrl = "https://\($fqdn)/" |
     .redirectUris = ["https://\($fqdn)/*", "https://\($fqdn)/web/*"] |
     .webOrigins = ["https://\($fqdn)"] |
     .attributes["post.logout.redirect.uris"] = "https://\($fqdn)/"' \
    /home/config/oidc-import.json > /etc/gromox/oidc-import.json
else
  rm -f /etc/gromox/keycloak.json /etc/gromox/oidc-import.json
fi

# ── Let's Encrypt renewal ─────────────────────────────────────────
if [ "${SSL_INSTALL_TYPE}" = "2" ]; then
  # On an actual renewal, rebuild the bundle that nginx, postfix and the
  # gromox http/imap/pop3 daemons read (certbot only refreshes the files
  # under /etc/letsencrypt/live) and restart the TLS services.
  # $RENEWED_LINEAGE is set by certbot to the renewed cert's live directory.
  cat > /usr/local/bin/grommunio-cert-deploy <<'DEPLOY'
#!/bin/bash
[ -n "${RENEWED_LINEAGE}" ] || exit 0
cp -f "${RENEWED_LINEAGE}/fullchain.pem" /etc/grommunio-common/ssl/server-bundle.pem
cp -f "${RENEWED_LINEAGE}/privkey.pem" /etc/grommunio-common/ssl/server.key
chown gromox:gromox /etc/grommunio-common/ssl/server-bundle.pem /etc/grommunio-common/ssl/server.key 2>/dev/null || true
chmod 0644 /etc/grommunio-common/ssl/server-bundle.pem
chmod 0600 /etc/grommunio-common/ssl/server.key
/usr/local/bin/supervisorctl restart gromox-http gromox-imap gromox-pop3 postfix
DEPLOY
  chmod +x /usr/local/bin/grommunio-cert-deploy

  # Renew on the published HTTP port (host :80 -> container :8081). nginx owns
  # 8081, so free it only while a renewal actually runs: the pre/post hooks
  # fire only when at least one certificate is due. cron's default PATH does
  # not contain /usr/local/bin (supervisorctl), hence the explicit PATH.
  cat > /etc/cron.d/certbot-renew <<'EOF'
SHELL=/bin/bash
PATH=/usr/local/sbin:/usr/local/bin:/usr/sbin:/usr/bin:/sbin:/bin
MAILTO=""
0 */12 * * * root /usr/bin/certbot renew --quiet --standalone --http-01-port 8081 --pre-hook '/usr/local/bin/supervisorctl stop nginx' --deploy-hook /usr/local/bin/grommunio-cert-deploy --post-hook '/usr/local/bin/supervisorctl start nginx' >>/var/log/certbot-renew.log 2>&1
EOF
  chmod 0644 /etc/cron.d/certbot-renew
else
  rm -f /etc/cron.d/certbot-renew
fi

# ── Periodic jobs (replacing the packages' systemd timers) ────────
{
  echo "SHELL=/bin/bash"
  echo "PATH=/usr/local/sbin:/usr/local/bin:/usr/sbin:/usr/bin:/sbin:/bin"
  # no local mailbox for cron output; failures are visible in the job logs
  echo 'MAILTO=""'
  # grommunio-web full-text search indexes: user groindex with group groweb
  # like the packaged unit, so grommunio-web can read the indexes
  if [ -n "${INDEX_SCHEDULE}" ] && [ -x /usr/bin/grommunio-index ]; then
    echo "${INDEX_SCHEDULE} root sudo -u groindex -g groweb /usr/bin/grommunio-index -Aq >>/var/log/grommunio-index.log 2>&1"
  fi
  [ -x /usr/libexec/grommunio-web/session-cleanup ] && \
    echo "*/15 * * * * groweb /usr/libexec/grommunio-web/session-cleanup >/dev/null 2>&1"
  # purge soft-deleted items and orphaned attachments (gromox-cleaner.timer);
  # the parentheses are gromox-mbop arguments, hence quoted for the shell
  PURGETIME=$(sed -n 's/^softdelete_purgetime[[:space:]]*=[[:space:]]*//p' /etc/gromox/gromox.cfg 2>/dev/null | tail -1)
  echo "30 3 * * * root /usr/sbin/gromox-mbop -v foreach.here.mb '(' purge-softdelete -t ${PURGETIME:-30d} -r / ')' '(' purge-datafiles ')' >>/var/log/gromox-cleaner.log 2>&1"
  [ -x /usr/sbin/grommunio-spam-run.sh ] && \
    echo "40 4 * * * root /usr/sbin/grommunio-spam-run.sh >/dev/null 2>&1"
} > /etc/cron.d/grommunio
chmod 0644 /etc/cron.d/grommunio
touch /var/log/grommunio-index.log /var/log/gromox-cleaner.log
